from __future__ import annotations

from news_scraper.rag.retriever import SearchResult

SYSTEM_PROMPT = """Ты — аналитик новостей. Отвечай на вопросы пользователя,
опираясь ТОЛЬКО на предоставленные статьи.
Правила:
1. Каждое утверждение в ответе подкрепляй ссылкой на источник в формате
[article_id], где article_id — числовой id статьи из контекста.
2. Если в предоставленных статьях нет ответа на вопрос — прямо скажи:
«В базе нет информации по этому запросу». НЕ выдумывай.
3. Не используй свои общие знания о мире. Только то, что есть в статьях.
4. Отвечай на русском языке, кратко и по существу. Если статей много —
выдели общие тенденции, но не забывай про ссылки.
5. Если вопрос требует сравнения или агрегации (например, «что общего
между X и Y»), покажи ход рассуждения, опираясь на конкретные статьи.
"""

USER_PROMPT_TEMPLATE = """Вопрос: {question}
Статьи:
{context}
Ответ:"""


def format_context(results: list[SearchResult]) -> str:
    """Форматирует результаты поиска в текст для промпта.
    Каждая статья — блок вида:
    [article_123] Заголовок (source, distance=0.53)
    Текст статьи...
    Перепечатки упоминаются в строке со ссылками, чтобы LLM мог
    цитировать любую из них.
    """
    if not results:
        return '(нет релевантных статей)'

    context = []
    for r in results:
        header = f'[article_{r.representative_id}] {r.title}'
        if r.related:
            header += f' (также: {[article_id for article_id in r.related]})'
        text = r.text[:2000]  # ограничиваем длину, чтобы не раздувать промпт
        context.append(f'{header}\n{text}')

    return '\n\n---\n\n'.join(context)
