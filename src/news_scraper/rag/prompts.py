from __future__ import annotations

from news_scraper.rag.retriever import SearchResult

SYSTEM_PROMPT = """Ты — аналитик новостей. Твоя задача — отвечать на
вопросы пользователя, опираясь на предоставленные статьи.
Как работать:
1. Прочитай все статьи в контексте.
2. Пойми, что спрашивает пользователь. Вопрос может быть сформулирован
по-разному — ищи смысл, а не буквальные совпадения.
3. Сформируй ответ, опираясь на факты из статей. Каждое утверждение
подкрепляй ссылкой [article_N].
4. Если в статьях действительно нет информации по теме — коротко
сообщи об этом своими словами, не пытайся ничего придумать.
Формат ответа:
- На русском языке.
- Кратко, 3-6 предложений.
- Со ссылками [article_N] на источники.
- Если статей несколько — выдели общее или различия.
"""
USER_PROMPT_TEMPLATE = """Вопрос: {question}
Статьи:
{context}
Ответ:"""


def format_context(results: list[SearchResult]) -> str:
    """Форматирует результаты поиска в текст для промпта.
    Каждая статья — блок вида:
    [article_123] Заголовок (source, distance=0.53)
    Текст статьи...
    Перепечатки упоминаются в строке со ссылками, чтобы LLM мог
    цитировать любую из них.
    """
    if not results:
        return '(нет релевантных статей)'

    context = []
    for r in results:
        header = f'[article_{r.representative_id}] {r.title}'
        if r.related:
            header += f' (также: {[article_id for article_id in r.related]})'
        text = r.text[:2000]  # ограничиваем длину, чтобы не раздувать промпт
        context.append(f'{header}\n{text}')

    return '\n\n---\n\n'.join(context)
